function mulberry32(a) {
  return () => {
    a |= 0
    a = (a + 0x6d2b79f5) | 0
    let t = Math.imul(a ^ (a >>> 15), 1 | a)
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}

function alongRoute(pts, dist, out) {
  for (let i = 1; i < pts.length; i++) {
    const seg = pts[i].distanceTo(pts[i - 1])
    if (dist <= seg || i === pts.length - 1) return out.copy(pts[i - 1]).lerp(pts[i], Math.min(1, dist / seg))
    dist -= seg
  }
  return out.copy(pts[pts.length - 1])
}

function routeDistance(t, speed, accel = 0.55) {
  if (t <= 0) return 0
  if (t < accel) return (speed * t * t) / (2 * accel)
  return speed * (t - accel / 2)
}

/** Inverse of routeDistance: seconds to cover `d` yards. */
function routeTime(d, speed, accel = 0.55) {
  if (d <= (speed * accel) / 2) return Math.sqrt((2 * d * accel) / speed)
  return d / speed + accel / 2
}

function angleLerp(a, b, k) {
  let d = ((b - a + Math.PI) % (Math.PI * 2)) - Math.PI
  if (d < -Math.PI) d += Math.PI * 2
  return a + d * k
}

/** How play-by-play names a player: the real name when there's a roster, else the jersey number. */
const who = (p) => p.name ?? `#${p.number}`

const isDefBack = (p) => p.role === 'CB' || p.role === 'S' || p.role === 'LB'
const skillPlayer = (p) => p.role !== 'OL' && p.role !== 'C' && p.role !== 'DL'

/** How a player reacts after the whistle: the scorer dances, the beaten DBs hold their heads. */
function reaction(p, { good, kind, td, scorer, picked }) {
  if (p.team === 'off') {
    if (scorer) return p.number % 2 ? 'Dance' : 'Flex'
    if (good) return skillPlayer(p) ? 'Celebrate' : td ? 'Clap' : 'Idle'
    if (kind === 'interception' && (p.role === 'QB' || p.role === 'WR')) return 'Dejected'
    return 'Idle'
  }
  if (picked) return 'Dance'
  if (!good) return isDefBack(p) ? 'Celebrate' : kind === 'sack' || kind === 'interception' ? 'Clap' : 'Idle'
  return td && isDefBack(p) ? 'Dejected' : 'Idle'
}

export class PlaySim {
  constructor() {
    this.timeScale = 1
    this.camMode = 'broadcast'
    this.reset()
  }

  /**
   * play: playbook id. reads: receiver keys in progression order (defaults to the play's).
   * flip: mirror the formation and play to the other side. coverage: { call, shown, key }.
   * situation: { clock } for clock-aware AI.
   * roster: optional real lineup { off: { qb: [number, name], ... }, def: { DL0: [...], ... } } (labels only:
   * it changes jersey numbers and names, never the play, so seeds replay the same).
   */
  reset({ play = 'dig', seed = 1, los = LOS, toGo = 10, coverage = null, situation = {}, difficulty = 0, reads = null, flip = false, roster = null, inputs = null } = {}) {
    this.roster = roster
    // live controls: commands land on the next fixed step and are logged with their sim time, so an
    // instant replay (or the same Daily with the same taps) plays out identically
    this.queue = []
    this.inputLog = []
    this.replayInputs = inputs ? inputs.map((e) => ({ ...e })) : null
    this.manual = false // any QB input hands the decisions to the player for the rest of the dropback
    this.spikeCall = false
    this.los = los
    this.firstDown = Math.min(los + toGo, GOAL_LINE)
    this.play = PLAYS[play] ?? PLAYS.dig
    this.seed = seed
    this.rng = mulberry32(seed)
    this.coverage = coverage ?? { call: 'cover3', shown: 'cover3' }
    this.situation = situation
    this.difficulty = difficulty
    this.flip = flip ? -1 : 1
    this.t = 0
    this.phase = 'presnap'
    this.players = []
    this.events = []
    this.message = null
    this.result = null
    this.catchTime = Infinity
    this.deadTime = Infinity
    this.tackleTime = Infinity
    this.throwAt = Infinity
    this.hurried = false
    this.pressured = false
    this.carrier = null
    this.tackler = null
    this.interceptor = null
    this.aim = null
    this.target = null
    this.readIdx = 0
    this.how = null
    this.wantThrow = null

    const r = (a, b) => a + (b - a) * this.rng()
    this.r = r
    const pb = this.play
    const isRun = this.play.type === 'run'
    const route = (pts) => pts.map(([x, z]) => V(x, Math.min(END_LINE, this.los + z)))
    // a real lineup swaps in jersey numbers and names by slot
    const label = (side, slot, extra) => {
      const real = roster?.[side]?.[slot]
      return real ? { ...extra, number: real[0], name: real[1] } : extra
    }
    let olSlot = 0
    const off = (role, x, dz, extra = {}) => {
      const slot = extra.key ?? (role === 'C' ? 'C' : role === 'OL' ? `OL${++olSlot}` : null)
      return this.add('off', role, x, this.los + dz, 0, label('off', slot, extra))
    }
    const defSlot = { DL: 0 }
    const def = (role, x, dz, extra = {}) => {
      const slot = extra.slot ?? (role === 'DL' ? `DL${defSlot.DL++}` : null)
      return this.add('def', role, x, this.los + dz, Math.PI, label('def', slot, extra))
    }

    // ------------------------------------------------ offense
    this.center = off('C', 0, -0.9, { number: 55, anim: 'Block' })
    off('OL', 1.6, -1.0, { number: 66, anim: 'Stance' })
    off('OL', -1.6, -1.0, { number: 67, anim: 'Stance' })
    off('OL', 3.2, -1.2, { number: 71, anim: 'Stance' })
    off('OL', -3.2, -1.2, { number: 75, anim: 'Stance' })
    this.qb = off('QB', 0, -5, { number: 8, anim: 'Shotgun', feel: r(0.08, 0.3), key: 'qb' })
    this.stareDown = this.rng() < 0.12 // sometimes the QB locks onto his first read no matter what
    const starts = { rb: [1.6, -5, 22, 'RB'], te: [-4.8, -1.3, 87, 'TE'], x: [17, -1, 18, 'WR'], z: [-14, -1.5, 11, 'WR'], slot: [9, -1.5, 13, 'WR'] }
    const speeds = { rb: 6.4, te: 6.2, x: r(7.8, 8.4), z: r(7.9, 8.5), slot: r(7.6, 8.1) }
    const startsAt = { x: 0.35, z: 0.35, slot: 0.35, te: 0.55, rb: pb.family === 'quick' ? 0.55 : 0.9 }
    for (const [k, [x, dz, number, role]] of Object.entries(starts)) {
      const pts = pb.routes?.[k]
      this[k] = off(role, x, dz, { number, key: k, anim: 'Stance', route: pts ? route(pts) : null, routeStart: pts ? startsAt[k] : 99, speed: speeds[k] })
    }
    if (isRun) {
      const run = pb.run
      this.holeX = run.hole
      const carrier = this[run.carrier] ?? this.qb
      carrier.runPath = route(run.path)
      if (run.carrier === 'rb') {
        this.rb.route = carrier.runPath
        this.rb.routeStart = run.draw ? 0.6 : SNAP_TIME + 0.05
        this.rb.speed = run.toss ? 7 : 6.5
      }
      if (run.lead) {
        const lead = this[run.lead]
        lead.route = route([[1.6, -5], [this.holeX, -1.5], [this.holeX, 2]])
        lead.routeStart = SNAP_TIME
        lead.speed = 6.6
        lead.leadBlock = true
      }
      for (const k of ['x', 'z', 'slot']) {
        // receivers block downfield on runs
        this[k].route = route([[starts[k][0], starts[k][1]], [starts[k][0] * 0.85, 5]])
        this[k].routeStart = 0.35
        this[k].speed = 5.5
        this[k].runBlocker = true
      }
      if (this.te) this.te.routeStart = 99
    }

    // offensive "hot" adjustment: if the defense shows the all-out blitz, keep the back and tight end in
    this.maxProtect = this.coverage.shown === 'blitz' && !isRun
    if (this.maxProtect) {
      this.rb.routeStart = 99
      this.te.routeStart = 99
    }

    // ------------------------------------------------ defense (aligned to what they *show*)
    const align = ALIGN[this.coverage.shown] ?? ALIGN.cover3
    const D = {}
    const dlNumbers = [93, 97, 91, 99]
    ;[[-0.9, 1.1], [0.9, 1.1], [-3.8, 1.1], [3.8, 1.1]].forEach(([x, dz], i) => {
      D[`DL${i}`] = def('DL', x, dz, { number: dlNumbers[i], anim: 'Stance', speed: r(5.6, 6.4), shed: (isRun ? r(2.1, 3.3) : r(1.1, 3.2)) - difficulty * 0.12 })
    })
    D.MLB = def('LB', ...align.MLB, { slot: 'MLB', number: 54, anim: 'Ready', speed: r(6.9, 7.6) })
    D.SLB = def('LB', ...align.SLB, { slot: 'SLB', number: 50, anim: 'Ready', speed: r(6.8, 7.5) })
    D.WLB = def('LB', ...align.WLB, { slot: 'WLB', number: 52, anim: 'Ready', speed: r(6.8, 7.5) })
    D.CBX = def('CB', ...align.CBX, { slot: 'CBX', number: 24, anim: 'Ready', speed: r(7.8, 8.6) })
    D.CBZ = def('CB', ...align.CBZ, { slot: 'CBZ', number: 21, anim: 'Ready', speed: r(7.8, 8.6) })
    D.SS = def('S', ...align.SS, { slot: 'SS', number: 31, anim: 'Ready', speed: r(7.5, 8.3) })
    D.FS = def('S', ...align.FS, { slot: 'FS', number: 29, anim: 'Ready', speed: r(7.7, 8.5) })
    for (const p of Object.values(D)) {
      p.react = r(0.12, 0.42) - difficulty * 0.03
      if (isRun && p.role !== 'DL') p.react += pb.run.draw ? 0 : r(0.25, 0.9) // the play fake freezes the second level
      p.tackle = r(0.72, 0.9) + difficulty * 0.02
      p.blanket = this.rng() < 0.33 + difficulty * 0.05
      p.zoneW = r(0.25, 0.6)
    }
    this.D = D
    this.assignDefense(this.coverage.call)
    this.applyKey(this.coverage.key)
    if (isRun) {
      // receivers stalk-block the defensive back on their side
      const taken = new Set()
      for (const k of ['x', 'slot', 'z']) {
        const wr = this[k]
        let best = null
        let bd = Infinity
        for (const d of [D.CBX, D.CBZ, D.SS, D.FS, D.SLB, D.WLB]) {
          const dd = Math.abs(d.start.x - wr.start.x) + Math.max(0, d.start.z - this.los - 8)
          if (!taken.has(d) && dd < bd) (bd = dd), (best = d)
        }
        if (best) {
          taken.add(best)
          wr.blocking = best
          best.blocker = wr
          best.shedAt = r(2.2, 3.4)
        }
      }
    }

    // ------------------------------------------------ mirror everything for a flipped play
    if (this.flip < 0) {
      for (const p of this.players) {
        p.pos.x *= -1
        p.start.x *= -1
        for (const pts of [p.route, p.runPath]) if (pts && !pts.flipped) (pts.forEach((v) => (v.x *= -1)), (pts.flipped = true))
        if (p.assign?.spot && !p.assign.spot.flipped) (p.assign.spot.x *= -1), (p.assign.spot.flipped = true)
      }
      if (this.holeX != null) this.holeX *= -1
    }

    // ------------------------------------------------ read progression
    if (this.play.type === 'pass') {
      const eligible = eligibleFor(this.play.id)
      const order = (reads ?? this.play.reads).filter((k) => eligible.includes(k) && this[k].routeStart < 50)
      for (const k of this.play.reads) if (!order.includes(k) && eligible.includes(k) && this[k].routeStart < 50) order.push(k)
      const dropEnd = 0.45 + this.play.drop * 0.11
      let prev = 0
      this.reads = order.slice(0, 3).map((k) => {
        const p = this[k]
        const firstLeg = p.route[1].distanceTo(p.route[0])
        const breakT = p.routeStart + routeTime(Math.min(firstLeg, 14), p.speed)
        const at = Math.max(dropEnd + 0.05, breakT + 0.05, prev + 0.4)
        prev = at
        return { key: k, p, at }
      })
      this.dropEnd = dropEnd
      this.throwAt = this.reads[0]?.at ?? 1.5
    }

    this.ball = {
      pos: new THREE.Vector3(0, 0.15, this.los),
      dir: new THREE.Vector3(0, 0, 1),
      state: 'ground',
      holder: null,
      from: new THREE.Vector3(),
      to: new THREE.Vector3(),
      t0: 0,
      t1: 0,
      arc: 0,
      vel: new THREE.Vector3(),
    }
  }

  assignDefense(call) {
    const { D, los } = this
    const zone = (x, dz, deep = false, range = 13) => ({ type: 'zone', spot: V(x, Math.min(END_LINE, los + dz)), deep, range })
    const man = (target, press = false) => ({ type: 'man', target, press })
    const rush = { type: 'rush' }
    for (let i = 0; i < 4; i++) D[`DL${i}`].assign = rush
    const A = {
      cover1: { CBX: man(this.x, true), CBZ: man(this.z, true), SS: man(this.slot), SLB: man(this.rb), WLB: man(this.te), MLB: zone(0, 4), FS: zone(0, 17, true, 20) },
      cover2: { CBX: zone(18, 5), CBZ: zone(-17, 5), SS: zone(12, 19, true, 17), FS: zone(-12, 19, true, 17), MLB: zone(0, 9), SLB: zone(7, 8), WLB: zone(-7, 8) },
      tampa2: { CBX: zone(18, 5), CBZ: zone(-17, 5), SS: zone(12, 19, true, 17), FS: zone(-12, 19, true, 17), MLB: zone(0, 15, true, 10), SLB: zone(8, 8), WLB: zone(-8, 8) },
      cover3: { CBX: zone(16, 17, true), CBZ: zone(-15, 17, true), FS: zone(0, 19, true, 20), SS: zone(12, 6), SLB: zone(5, 8), MLB: zone(-1, 8), WLB: zone(-11, 6) },
      cover4: { CBX: zone(16, 18, true, 11), CBZ: zone(-15, 18, true, 11), SS: zone(7, 17, true, 11), FS: zone(-6, 17, true, 11), SLB: zone(10, 6), MLB: zone(0, 7), WLB: zone(-10, 6) },
      firezone: { CBX: zone(16, 17, true), CBZ: zone(-15, 17, true), FS: zone(0, 19, true, 20), SS: zone(12, 6), WLB: zone(-11, 6), SLB: rush, MLB: rush },
      blitz: { CBX: man(this.x, true), CBZ: man(this.z, true), SS: man(this.slot, true), FS: man(this.te), SLB: man(this.rb), MLB: rush, WLB: rush },
      prevent: { CBX: zone(17, 22, true), CBZ: zone(-16, 22, true), SS: zone(7, 28, true), FS: zone(-7, 28, true), MLB: zone(0, 12), SLB: zone(10, 10), WLB: zone(-10, 10) },
    }[call] ?? {}
    for (const [k, a] of Object.entries(A)) D[k].assign = a
    if (call === 'prevent') D.DL3.assign = zone(5, 5) // three-man rush
    if (call === 'firezone') D.DL2.assign = zone(-6, 4) // zone blitz: a lineman drops into the hook
    for (const p of Object.values(D)) if (p.assign.type === 'rush' && p.role === 'LB') p.blitzer = true
  }

  /**
   * Keying on a concept family the offense keeps running (or a human defender's guess).
   * Right guess: quicker reads, tighter coverage, a defender sitting in that family's window.
   * Wrong guess: out of position and a step slow.
   */
  applyKey(key) {
    const family = key?.family ?? (key?.play ? PLAYS[key.play]?.family : null)
    this.key = key && key.s > 0 && family ? { ...key, family } : null
    if (!this.key) return
    const { D } = this
    const s = this.key.s
    const hit = family === this.play.family
    for (const p of Object.values(D)) {
      if (hit) {
        p.react = Math.max(0.04, p.react - 0.2 * s)
        if (this.rng() < 0.35 * s) p.blanket = true
      } else p.react += 0.12 * s
    }
    const zoneAt = (k, x, dz, deep = false) => {
      const a = D[k].assign
      if (a.type !== 'zone') return false
      a.spot.set(x, 0, Math.min(END_LINE, this.los + dz))
      a.deep = deep
      return true
    }
    switch (family) {
      case 'quick':
        if (!zoneAt('CBX', 17.5, 4) && !zoneAt('SS', 16, 4)) D.SS.blanket = true
        zoneAt('WLB', -12, 4) || (D.CBZ.blanket = true)
        break
      case 'mid':
        if (!zoneAt('MLB', 3, 12)) zoneAt('FS', 3, 13)
        zoneAt('SLB', 9, 11)
        D.CBX.blanket = true
        break
      case 'deep':
        zoneAt('FS', -9, 22, true) || zoneAt('SS', -8, 22, true)
        if (D.CBZ.assign.type === 'man') D.CBZ.blanket = true
        else zoneAt('CBZ', -15, 21, true)
        break
      case 'run':
        zoneAt('SS', 2, 5)
        zoneAt('MLB', -0.5, 3.5)
        for (const p of Object.values(D)) {
          if (p.role === 'LB' && hit) p.react = 0.05
          if (p.role === 'DL') p.shed -= 0.6 * s
        }
        break
      default:
    }
  }

  add(team, role, x, z, yaw, extra) {
    const p = {
      id: this.players.length,
      team,
      role,
      pos: V(x, z),
      start: V(x, z),
      vel: new THREE.Vector3(),
      yaw,
      face: null,
      anim: 'Idle',
      animScale: 1,
      locked: false,
      down: false,
      react: 0,
      cutBias: 0,
      blocker: null,
      shedAt: Infinity,
      blocking: null,
      ...extra,
    }
    this.players.push(p)
    return p
  }

  emit(type, data = {}) {
    this.events.push({ type, t: this.t, ...data })
  }

  snap() {
    if (this.phase !== 'presnap') return
    this.phase = 'live'
    this.t = 0
    const b = this.ball
    b.state = 'snap'
    b.from.copy(b.pos)
    b.t0 = 0
    b.t1 = SNAP_TIME
    b.arc = 0.4
    this.setupProtection()
    this.emit('snap')
  }

  setupProtection() {
    const rushers = this.players.filter((p) => p.team === 'def' && p.assign?.type === 'rush')
    const blockers = this.players.filter((p) => p.role === 'OL' || p.role === 'C')
    const isRun = this.play.type === 'run'
    if (this.te.routeStart > 50) blockers.push(this.te)
    if (this.rb.routeStart > 50 && !isRun) blockers.push(this.rb)
    rushers.sort((a, b) => Math.abs(a.start.x) - Math.abs(b.start.x))
    const free = [...blockers]
    for (const d of rushers) {
      let best = null
      let bd = Infinity
      for (const o of free) {
        const dd = Math.abs(o.start.x - d.start.x) + (o.role === 'RB' ? 2 : 0)
        if (dd < bd) (bd = dd), (best = o)
      }
      if (!best || bd > 6) continue
      free.splice(free.indexOf(best), 1)
      best.blocking = d
      d.blocker = best
      d.shedAt = d.role === 'DL' ? d.shed : this.r(1.1, 1.9)
    }
  }

  // ------------------------------------------------------------------ live controls
  /** Queue a player command: throw {key}, away, scramble, pump, juke {dir}, spin, sideline, slide, spike. */
  input(cmd) {
    if (this.replayInputs) return false // a replay re-runs the logged taps
    if (cmd.type === 'spike' && this.phase === 'presnap') {
      this.spikeCall = true
      this.inputLog.push({ t: 0, ...cmd })
      return true
    }
    if (this.phase !== 'live') return false
    this.queue.push(cmd)
    return true
  }

  applyInputs(t) {
    const due = this.replayInputs ? this.replayInputs.filter((e) => !e.done && e.t <= t + 1e-6) : this.queue.splice(0)
    for (const e of due) {
      if (this.replayInputs) e.done = true
      if (e.type === 'spike') {
        this.spikeCall = true
        continue
      }
      if (this.command(e, t) && !this.replayInputs) this.inputLog.push({ t, ...e })
    }
  }

  /** What the player can do right now (for the on-screen controls). */
  controls() {
    if (this.phase !== 'live') return null
    const qb = this.qb
    const b = this.ball
    if (this.play.type === 'pass' && !qb.threw && !this.carrier && !this.spikeCall && (b.holder === qb || b.state === 'snap')) {
      return {
        mode: 'qb',
        reads: (this.reads ?? []).map((r, i) => ({ key: r.key, n: i + 1, name: r.p.name ?? null, number: r.p.number, open: this.openness(r.p, false), pos: r.p.pos })),
        ready: this.t >= Math.min(this.dropEnd ?? 0, SNAP_TIME + 0.45),
        manual: this.manual,
        pumping: (qb.pumpUntil ?? 0) > this.t,
        queued: this.wantThrow?.key ?? null,
      }
    }
    const c = this.carrier
    if (c && c.team === 'off' && this.t >= this.catchTime + 0.15 && !(this.play.type === 'run' && c.pos.z < this.los + 1.2 && c.runPath)) {
      return { mode: 'run', name: c.name ?? `#${c.number}`, juking: c.juke && this.t < c.juke.until, cooldown: Math.max(0, (c.moveReady ?? 0) - this.t), sideline: !!c.toSideline }
    }
    return null
  }

  command(e, t) {
    const qb = this.qb
    const b = this.ball
    const holding = b.holder === qb && !qb.threw && !this.carrier && this.play.type === 'pass'
    switch (e.type) {
      case 'throw': {
        const r = this.reads?.find((x) => x.key === e.key)
        if (!r || !(holding || b.state === 'snap')) return false
        this.manual = true
        this.wantThrow = r.p
        return true
      }
      case 'away':
        if (!holding || t < SNAP_TIME + 0.3) return false
        this.manual = true
        this.throwAway(t)
        this.message = 'Thrown away. Live to fight another down.'
        return true
      case 'scramble':
        if (!holding) return false
        this.manual = true
        this.giveTo(qb, t, 'QB takes off!', true)
        // break contain toward the side with fewer free rushers, angling upfield
        let lean = 0
        for (const d of this.players) if (d.team === 'def' && !d.down && !this.isEngaged(d) && d.pos.z < this.los + 6) lean += Math.sign(d.pos.x - qb.pos.x) / (1 + d.pos.distanceTo(qb.pos))
        qb.escape = V(qb.pos.x + (lean > 0 ? -5.5 : 5.5), this.los + 0.5)
        return true
      case 'pump': {
        if (!holding || (qb.pumpUntil ?? 0) > t || t < SNAP_TIME + 0.3) return false
        this.manual = true
        qb.pumpUntil = t + 0.4
        this.oneShot(qb, 'Throw')
        // defenders keyed on the read he's looking at jump it, unless they're sticky in coverage
        const look = (this.bestRead(false)?.p ?? this.reads[0]?.p)
        let bit = 0
        for (const d of this.players) {
          if (d.team !== 'def' || d.down || d.assign?.type === 'rush' || !look) continue
          if (d.pos.distanceTo(look.pos) > 9) continue
          if (this.rng() < (d.blanket ? 0.3 : 0.65)) {
            d.frozenUntil = t + 0.55
            bit++
          }
        }
        this.message = bit ? `Pump fake! ${bit > 1 ? 'They' : 'He'} bit!` : 'Pump fake... nobody bit.'
        this.emit('pump')
        return true
      }
      case 'juke':
      case 'spin': {
        const c = this.carrier
        if (!c || c.team !== 'off' || (c.moveReady ?? 0) > t || t < this.catchTime + 0.15) return false
        c.moveReady = t + 0.9
        if (e.type === 'spin') {
          c.spinUntil = t + 0.45
          this.message = 'Spin move!'
        } else {
          // from the camera, "left" is world +x (the field is mirrored)
          c.juke = { dir: e.dir, until: t + 0.32 }
          let fooled = 0
          for (const d of this.players) {
            if (d.team !== 'def' || d.down || this.isEngaged(d) || d.pos.distanceTo(c.pos) > 4.5) continue
            if (this.rng() < 0.6 - (d.tackle - 0.8)) {
              d.frozenUntil = t + 0.5
              fooled++
            }
          }
          this.message = fooled ? 'JUKED HIM!' : 'Juke!'
        }
        this.emit('move')
        return true
      }
      case 'sideline': {
        const c = this.carrier
        if (!c || c.team !== 'off') return false
        c.toSideline = true
        this.message = 'Heading for the sideline!'
        return true
      }
      case 'slide': {
        const c = this.carrier
        if (!c || c.team !== 'off' || t < this.catchTime + 0.15) return false
        this.endPlay(t, 'tackle')
        const { gain, first } = this.result
        this.message = `${who(c)} gets down after ${gain} yard${Math.abs(gain) === 1 ? '' : 's'}${first ? ' — FIRST DOWN!' : ''}`
        c.pendingFall = t + 0.05
        c.sliding = true
        this.emit('slide')
        return true
      }
      default:
        return false
    }
  }

  /** Clock-stopping spike: costs a down, takes about a second. */
  spike(t) {
    const b = this.ball
    const qb = this.qb
    this.oneShot(qb, 'Spike')
    qb.threw = true
    b.state = 'loose'
    b.holder = null
    b.vel.set(0, -6, 1.5)
    this.phase = 'dead'
    this.deadTime = t
    this.result = { good: false, kind: 'spike', gain: 0, first: false, spot: this.los, elapsed: 1 }
    this.message = 'Spiked! Clock stopped.'
    this.emit('spike')
  }

  // ------------------------------------------------------------------ steering
  look(p, dx, dz) {
    p.lookPt ??= new THREE.Vector3()
    p.face = p.lookPt.set(p.pos.x + dx, 0, p.pos.z + dz)
  }

  steer(p, target, maxSpeed, dt, accel = 22) {
    if (this.isEngaged(p)) maxSpeed = Math.min(maxSpeed, 0.9)
    tmp.subVectors(target, p.pos)
    tmp.y = 0
    const dist = tmp.length()
    const want = Math.min(maxSpeed, dist * 3)
    if (dist > 1e-4) tmp.multiplyScalar(want / dist)
    else tmp.set(0, 0, 0)
    tmp2.subVectors(tmp, p.vel)
    const dv = tmp2.length()
    const maxDv = accel * dt
    if (dv > maxDv) tmp2.multiplyScalar(maxDv / dv)
    p.vel.add(tmp2)
    p.pos.addScaledVector(p.vel, dt)
  }

  brake(p, dt, rate = 10) {
    p.vel.multiplyScalar(Math.max(0, 1 - rate * dt))
    p.pos.addScaledVector(p.vel, dt)
  }

  isEngaged(p) {
    const b = p.blocker
    return !!b && !b.down && this.t < p.shedAt && b.pos.distanceTo(p.pos) < 1.3
  }

  followRoute(p, dt) {
    const prev = tmp2.copy(p.pos)
    alongRoute(p.route, routeDistance(this.t - p.routeStart, p.speed), p.pos)
    p.vel.subVectors(p.pos, prev).divideScalar(Math.max(dt, 1e-4))
  }

  routePosAt(p, t, out) {
    return alongRoute(p.route, routeDistance(t - p.routeStart, p.speed), out)
  }

  oneShot(p, clip) {
    p.anim = clip
    p.animScale = 1
    p.locked = true
    p.lockedAt = this.t
  }

  pursue(p, speed, dt) {
    const c = this.carrier
    if (this.t < this.catchTime + p.react) {
      this.brake(p, dt, 4)
      p.face = c.pos
      return
    }
    let tt = 0
    for (; tt < 2.5; tt += 0.1) {
      tmp3.copy(c.pos).addScaledVector(c.vel, tt)
      if (tmp3.distanceTo(p.pos) <= speed * tt + 0.8) break
    }
    tmp3.copy(c.pos).addScaledVector(c.vel, Math.min(tt, 1.6))
    tmp3.x = THREE.MathUtils.clamp(tmp3.x, -SIDELINE - 1, SIDELINE + 1)
    this.steer(p, tmp3, speed, dt)
    p.hold = this.isEngaged(p) ? 'Block' : null
    p.face = null
  }

  // ------------------------------------------------------------------ main step
  step(dt) {
    if (this.phase === 'presnap') return
    this.t += dt
    const t = this.t
    this.applyInputs(t)

    for (const p of this.players) {
      if (p.down) {
        this.brake(p, dt, 5)
        continue
      }
      if (this.phase === 'dead' || this.phase === 'over') {
        this.brake(p, dt, 4)
        const focus = this.carrier ?? this.interceptor ?? this.target
        p.face = focus && p !== focus ? focus.pos : null
        continue
      }
      if (p.team === 'def') this.actDefense(p, t, dt)
      else this[`act_${p.role}`]?.(p, t, dt)
    }
    for (const p of this.players) {
      if (p.team !== 'off') continue
      p.hist ??= []
      p.hist.push(p.pos.x, p.pos.z)
      if (p.hist.length > 80) p.hist.splice(0, 2)
    }

    this.separate()
    this.updateBall(t, dt)
    if (this.phase === 'live') {
      this.checkPressure(t)
      this.checkTackle(t)
      this.checkBoundaries(t)
    }
    this.updateFall(t)

    if (this.phase === 'dead' && t > this.deadTime + 1.1) this.finish()

    for (const p of this.players) this.pickAnim(p, dt)
  }

  finish() {
    this.phase = 'over'
    const good = this.result?.good
    const kind = this.result?.kind
    const td = kind === 'touchdown'
    const focus = this.carrier ?? this.interceptor ?? this.target
    for (const p of this.players) {
      if (p.down) continue
      p.locked = false
      p.face = focus && p !== focus ? focus.pos : null
      p.anim = reaction(p, { good, kind, td, scorer: td && p === this.carrier, picked: p === this.interceptor })
    }
  }

  separate() {
    const ps = this.players
    const R = 0.85
    const weight = (p) => (p.route && !p.runBlocker && !p.leadBlock && this.t >= p.routeStart && !this.carrier && p.team === 'off' && p.role !== 'RB' ? 0 : 1)
    for (let i = 0; i < ps.length; i++) {
      for (let j = i + 1; j < ps.length; j++) {
        const a = ps[i]
        const b = ps[j]
        if ((a === this.tackler && b === this.carrier) || (b === this.tackler && a === this.carrier)) continue
        const dx = b.pos.x - a.pos.x
        const dz = b.pos.z - a.pos.z
        const d2 = dx * dx + dz * dz
        if (d2 >= R * R || d2 < 1e-8) continue
        const d = Math.sqrt(d2)
        const aw = weight(a)
        const bw = weight(b)
        if (aw + bw === 0) continue
        const push = (R - d) / d / (aw + bw)
        a.pos.x -= dx * push * aw
        a.pos.z -= dz * push * aw
        b.pos.x += dx * push * bw
        b.pos.z += dz * push * bw
      }
    }
  }

  pickAnim(p, dt) {
    const speed = Math.hypot(p.vel.x, p.vel.z)
    let yawTarget = p.yaw
    if (p.face) yawTarget = Math.atan2(p.face.x - p.pos.x, p.face.z - p.pos.z)
    else if (speed > 0.4) yawTarget = Math.atan2(p.vel.x, p.vel.z)
    p.yaw = angleLerp(p.yaw, yawTarget, Math.min(1, dt * 10))

    if (p.locked || this.phase === 'over') return
    if (p.hold) {
      p.anim = p.hold
      p.animScale = 1
      return
    }
    // ball carrier moves (cosmetic: the sim already moved him)
    if (p.juke && this.t < p.juke.until) {
      p.anim = p.juke.dir > 0 ? 'JukeL' : 'JukeR'
      p.animScale = 1
      return
    }
    if (p.spinUntil > this.t) {
      p.anim = 'Spin'
      p.animScale = 1
      return
    }
    if (speed > 0.6) {
      const forward = Math.sin(p.yaw) * p.vel.x + Math.cos(p.yaw) * p.vel.z
      const carrying = this.ball.holder === p && this.ball.state === 'held'
      if (forward < -0.3 * speed) {
        // dropping back or backpedaling in coverage
        p.anim = 'Backpedal'
        p.animScale = THREE.MathUtils.clamp(speed / 5, 0.6, 1.5)
      } else if (p.team === 'def' && speed < 6 && Math.abs(forward) < 0.55 * speed) {
        // sliding sideways while keeping eyes on the play
        p.anim = 'Shuffle'
        p.animScale = THREE.MathUtils.clamp(speed / 4, 0.7, 1.5)
      } else {
        p.anim = carrying ? 'RunBall' : 'Run'
        p.animScale = THREE.MathUtils.clamp(speed / 6.5, 0.55, 1.45)
      }
    } else {
      p.anim = 'Idle'
      p.animScale = 1
    }
  }

  // ------------------------------------------------------------------ offense
  act_C(p, t, dt) {
    this.act_OL(p, t, dt)
  }

  act_OL(p, t, dt) {
    if (this.carrier && this.carrier !== this.qb && this.play.type !== 'run') return this.blockDownfield(p, t, dt, 3.5)
    if (this.carrier === this.qb && this.play.type !== 'run') return this.blockDownfield(p, t, dt, 3.5)
    const draw = this.play.run?.draw && !this.carrier
    if (this.play.type === 'run' && !draw) return this.runBlock(p, t, dt)
    this.passBlock(p, t, dt)
  }

  passBlock(p, t, dt) {
    p.hold = 'Block'
    const d = p.blocking
    if (d && !d.down) {
      tmp.subVectors(this.qb.pos, d.pos).setY(0).normalize().multiplyScalar(0.95).add(d.pos)
      tmp.z = Math.min(tmp.z, this.los - 0.4)
      this.steer(p, tmp, 4.6, dt, 26)
      p.face = d.pos
    } else {
      tmp.copy(p.start).setZ(p.start.z - Math.min(1.4, t * 1.2))
      this.steer(p, tmp, 2.5, dt)
      this.look(p, 0, 5)
    }
  }

  runBlock(p, t, dt) {
    if (this.carrier && this.carrier.pos.z > this.los + 2) return this.blockDownfield(p, t, dt, 3.5)
    p.hold = 'Block'
    const hole = this.holeX
    const d = p.blocking
    if (d && !d.down) {
      const reach = this.play.run?.toss ? Math.sign(hole) : 0
      const away = reach || Math.sign(d.pos.x - hole || p.start.x - hole || 1)
      tmp.copy(d.pos).add(tmp2.set(-away * (reach ? -0.5 : 0.35), 0, -0.75))
      this.steer(p, tmp, 4.4, dt, 26)
      p.face = d.pos
      return
    }
    let lb = null
    let ld = 9
    for (const dd of this.players) {
      if (dd.role !== 'LB' || dd.down || (dd.blocker && dd.blocker.blocking === dd)) continue
      const dist = dd.pos.distanceTo(p.pos)
      if (dist < ld) (ld = dist), (lb = dd)
    }
    if (lb && t > SNAP_TIME + 0.2) {
      p.blocking = lb
      lb.blocker = p
      lb.shedAt = t + this.r(0.7, 1.5)
      return
    }
    tmp.copy(p.start).setZ(p.start.z + Math.min(1.6, t * 1.5))
    if (Math.abs(p.start.x - hole) < 1.7) tmp.x += Math.sign(p.start.x - hole) * Math.min(0.9, t * 1.2)
    this.steer(p, tmp, 2.5, dt)
    this.look(p, 0, 5)
  }

  blockDownfield(p, t, dt, speed) {
    const c = this.carrier
    if (!p.blocking || p.blocking.down || p.blocking.pos.distanceTo(c.pos) > 9) {
      let best = null
      let score = Infinity
      for (const d of this.players) {
        if (d.team !== 'def' || d.down || (d.blocker && d.blocker !== p && !d.blocker.down && d.blocker.blocking === d)) continue
        const toBall = d.pos.distanceTo(c.pos)
        const toMe = d.pos.distanceTo(p.pos)
        if (toBall > 9 || toMe > 7) continue
        const s = toBall + toMe * 0.6
        if (s < score) (score = s), (best = d)
      }
      if (p.blocking && p.blocking.blocker === p) p.blocking.blocker = null
      p.blocking = best
      if (best) {
        best.blocker = p
        best.shedAt = t + this.r(0.45, 1.2)
      }
    }
    const d = p.blocking
    if (d) {
      tmp.subVectors(c.pos, d.pos).setY(0).normalize().multiplyScalar(0.9).add(d.pos)
      this.steer(p, tmp, speed + 2.5, dt, 20)
      p.hold = d.pos.distanceTo(p.pos) < 1.4 ? 'Block' : null
      p.face = p.hold ? d.pos : null
    } else {
      tmp.copy(c.pos).add(tmp2.set(p.start.x > c.pos.x ? 3 : -3, 0, -1))
      this.steer(p, tmp, speed, dt)
      p.hold = null
      p.face = null
    }
  }

  act_QB(p, t, dt) {
    const b = this.ball
    if (p === this.carrier) return this.actCarrier(p, t, dt)
    if (t < SNAP_TIME) return this.look(p, 0, 20)

    // ---- runs
    if (this.play.type === 'run') {
      const run = this.play.run
      if (run.carrier === 'qb') {
        if (b.holder === p && t >= SNAP_TIME + 0.05) this.giveTo(p, t, run.lead ? `#8 BLASTS it` : 'QB keeper')
        return
      }
      if (b.holder === p) {
        if (run.draw) {
          // sell the pass: drop like a pass play, then slip it to the back
          this.steer(p, tmp.set(0.3, 0, this.los - 6.5), 3.4, dt)
          this.look(p, 0, 20)
          if (t >= run.handoff + SNAP_TIME) {
            for (const d of this.players) if (d.assign?.type === 'rush' && d.blocker) d.shedAt = Math.max(d.shedAt, t + 0.7)
            this.giveTo(this.rb, t, 'Draw!')
          }
          return
        }
        this.steer(p, tmp.set(0.3 * this.flip, 0, this.los - 4.9), 2, dt)
        p.face = this.rb.pos
        const meshReady = t >= SNAP_TIME + run.handoff && (run.toss || this.rb.pos.distanceTo(p.pos) < 2.2) // a toss doesn't need the mesh
        if (meshReady || t >= SNAP_TIME + run.handoff + 0.4) this.giveTo(this.rb, t, run.toss ? 'Toss!' : 'Handoff!')
        return
      }
      this.steer(p, tmp.set(-4 * this.flip, 0, this.los - 7), 4.5, dt) // carry out the fake
      return
    }

    // ---- passes: drop, then work the progression
    if (this.spikeCall && b.holder === p && !p.threw && t >= SNAP_TIME + 0.12) return this.spike(t)
    if (b.holder !== p && p.threw) {
      this.brake(p, dt)
      if (p.locked && t > p.lockedAt + 1.25) p.locked = false
      return
    }
    if (p.threw) {
      this.brake(p, dt)
      p.face = this.aim.point
      if (b.state === 'held' && b.holder === p && t >= this.aim.release) this.release(t)
      return
    }
    // the player's call: throw as soon as he's set (a quick release cuts the drop short)
    const want = this.wantThrow
    if (want && b.holder === p && t >= Math.min(this.dropEnd, SNAP_TIME + 0.45) && t >= (p.pumpUntil ?? 0)) {
      this.wantThrow = null
      return this.startThrow(want, t)
    }
    if (t < this.dropEnd) {
      this.steer(p, tmp.set(0, 0, this.los - this.play.drop), 4.4, dt)
      return this.look(p, 0, 20)
    }
    this.brake(p, dt)
    if (b.holder !== p) return
    if (this.manual) {
      // your QB: eyes on the best option, waiting on you (hold it too long and you'll wear a sack)
      p.face = (this.bestRead(false)?.p ?? this.reads[0]?.p)?.pos ?? null
      return
    }
    const read = this.reads[this.readIdx]
    if (!read) return
    p.face = read.p.pos // eyes on the current read
    if (t < read.at && !this.pressured) return

    const last = this.readIdx === this.reads.length - 1
    const open = this.openness(read.p)
    const need = (this.readIdx === 0 ? (this.stareDown ? -1.4 : 0.4) : last ? -0.5 : 0.15) - (this.pressured ? 0.6 : 0)
    if (open >= need) return this.startThrow(read.p, t)
    if (this.pressured) {
      // no time: best available, a scramble, or throw it away
      const best = this.bestRead()
      if (best && best.open >= -0.6) return this.startThrow(best.p, t)
      if (this.laneOpen(p) && this.rng() < 0.65) return this.giveTo(p, t, 'QB scrambles!', true)
      if (t > 0.9) return this.throwAway(t)
      return
    }
    if (!last) {
      this.readIdx++
      const next = this.reads[this.readIdx]
      next.at = Math.max(next.at, t + 0.35)
      return
    }
    // checkdown covered too: hang in a beat, then find the best option
    if (t > read.at + 0.45) {
      const best = this.bestRead()
      // nothing there and green grass in front of him: take off
      if ((!best || best.open < -0.2) && this.laneOpen(p) && this.rng() < 0.6) return this.giveTo(p, t, 'QB scrambles!', true)
      if (best && best.open >= -0.9) return this.startThrow(best.p, t)
      if (t > read.at + 1.1) return this.throwAway(t)
    }
  }

  /**
   * How open a receiver would be if the ball came out now: predicted separation at the catch, using the
   * same rules the defenders follow (they keep doing their job until the ball is out and they react,
   * then break on it), minus the catch radius that decides contested balls. >0 = open.
   * The QB isn't perfect: a little noise means he sometimes sees a window that isn't there.
   */
  openness(R, noisy = true) {
    if (!R || R.down || !R.route) return -9
    this.planThrow(this.t, R, true)
    const { point, time } = this._probe
    const until = time - this.t
    const depth = point.z - this.los
    const reach = depth > 20 ? 2.8 : depth > 8 ? 2.2 : 1.6
    let nd = 9
    for (const d of this.players) {
      if (d.team !== 'def' || d.down || d.assign?.type === 'rush') continue
      const a = d.assign
      const readDelay = d.react + (a?.type === 'zone' && !d.blanket ? 0.25 : 0)
      const breakAt = THROW_RELEASE + readDelay
      tmp3.copy(d.pos).addScaledVector(d.vel, Math.min(until, breakAt))
      let dist = tmp3.distanceTo(point)
      const range = a?.type === 'man' ? 40 : a?.deep ? 22 : 16
      if (until > breakAt && dist < range) dist = Math.max(0, dist - (d.speed + 0.4) * (until - breakAt))
      // man defenders in his hip pocket are with him wherever he goes
      if (a?.type === 'man' && a.target === R) dist = Math.min(dist, d.pos.distanceTo(R.pos) * (d.blanket ? 0.6 : 1))
      nd = Math.min(nd, dist)
    }
    const misread = noisy ? (this.rng() - 0.5) * (this.pressured ? 2.2 : 1.3) : 0
    return nd - reach + misread
  }

  bestRead(noisy = true) {
    let best = null
    for (const r of this.reads) {
      const o = this.openness(r.p, noisy)
      if (!best || o > best.open) best = { p: r.p, open: o }
    }
    return best
  }

  laneOpen(qb) {
    for (const d of this.players) {
      if (d.team !== 'def' || d.down) continue
      const dz = d.pos.z - qb.pos.z
      if (dz > -0.5 && dz < 3.5 && Math.abs(d.pos.x - qb.pos.x) < 2.5 && !this.isEngaged(d)) return false
    }
    return true
  }

  startThrow(R, t) {
    this.target = R
    // forcing it to a covered first read: the defense reads his eyes and jumps it a beat early
    this.staredDown = this.readIdx === 0 && this.stareDown && this.openness(R) < 0
    if (this.staredDown) for (const d of this.players) if (d.team === 'def') d.react = Math.max(0.03, d.react - 0.22)
    this.planThrow(t, R)
    this.qb.threw = true
    this.oneShot(this.qb, 'Throw')
  }

  /** Hand the ball to (or keep it for) a runner. */
  giveTo(p, t, msg, scramble = false) {
    this.ball.holder = p
    this.carrier = p
    this.catchTime = t
    p.cutBias = (this.rng() - 0.5) * 0.6
    p.scramble = scramble
    this.message = msg
    this.how = p === this.qb ? (scramble ? 'scramble' : this.play.run?.lead ? 'blast' : 'keep') : 'run'
    this.emit(scramble ? 'scramble' : 'handoff')
  }

  throwAway(t) {
    const b = this.ball
    const qb = this.qb
    this.oneShot(qb, 'Throw')
    qb.threw = true
    b.state = 'loose'
    b.holder = null
    b.vel.set(Math.sign(qb.pos.x || 1) * 16, 6, 4)
    this.phase = 'dead'
    this.deadTime = t
    this.result = { good: false, kind: 'incomplete', gain: 0, first: false, spot: this.los, elapsed: t }
    this.message = 'Nobody open. Thrown away.'
    this.emit('incomplete')
  }

  act_WR(p, t, dt) {
    if (p === this.carrier) return this.actCarrier(p, t, dt)
    if (p.runBlocker && p.blocking && !p.blocking.down && t > p.routeStart) {
      // stalk block: get between your man and the ball, stay on him
      const d = p.blocking
      tmp.subVectors(this.carrier?.pos ?? this.qb.pos, d.pos).setY(0).normalize().multiplyScalar(0.9).add(d.pos)
      this.steer(p, tmp, 6.5, dt, 20)
      p.hold = d.pos.distanceTo(p.pos) < 1.4 ? 'Block' : null
      p.face = p.hold ? d.pos : null
      return
    }
    if (this.carrier) return this.blockDownfield(p, t, dt, 5)
    if (t < p.routeStart) {
      p.hold = 'Stance'
      return
    }
    p.hold = null
    p.face = null
    if (p === this.target && this.aim && this.ball.state === 'air' && t >= this.aim.time - 0.22 && !p.catching) {
      p.catching = true
      this.oneShot(p, 'Catch')
    }
    if (p.locked && t > p.lockedAt + 0.8) p.locked = false
    this.followRoute(p, dt)
  }

  act_TE(p, t, dt) {
    if (p === this.carrier) return this.actCarrier(p, t, dt)
    if (this.carrier) return this.blockDownfield(p, t, dt, 5)
    if (t < p.routeStart) {
      if (this.play.type === 'run' && !this.play.run.draw) return this.runBlock(p, t, dt)
      if (p.blocking) return this.passBlock(p, t, dt)
      p.hold = 'Block'
      return
    }
    this.act_WR(p, t, dt)
  }

  act_RB(p, t, dt) {
    if (p === this.carrier) return this.actCarrier(p, t, dt)
    if (p.leadBlock) {
      // lead blocker: through the hole, then take on the first linebacker
      if (t < p.routeStart) return
      if (!p.blocking && p.pos.z < this.los + 1) return this.followRoute(p, dt)
      return this.blockDownfield(p, t, dt, 5)
    }
    if (this.carrier) return this.blockDownfield(p, t, dt, 5)
    if (t < p.routeStart) {
      if (p.blocking && t > SNAP_TIME) return this.passBlock(p, t, dt)
      p.hold = t < SNAP_TIME ? 'Stance' : 'Block'
      return
    }
    if (this.play.type === 'run' && !this.carrier) {
      // get to the mesh point and wait there for the ball
      p.hold = null
      p.face = this.qb.pos
      return this.steer(p, p.runPath[1], this.play.run.toss ? 7 : 4, dt)
    }
    this.act_WR(p, t, dt)
  }

  /** Ball carrier: follow the designed run path, then score directions for open space. */
  actCarrier(p, t, dt) {
    if (p.locked && t > p.lockedAt + 0.62) p.locked = false
    const since = t - this.catchTime
    p.face = null
    // designed runs: hit the hole first
    if (p.runPath && this.play.type === 'run' && p.pos.z < this.los + 1.2) {
      p.pathIdx ??= 1
      while (p.pathIdx < p.runPath.length - 1 && p.runPath[p.pathIdx].distanceTo(p.pos) < 1.2) p.pathIdx++
      const fast = this.play.run.carrier === 'qb' ? 6.6 : 7.4
      // aim *through* the waypoint so he doesn't ease off at each one
      tmp.subVectors(p.runPath[p.pathIdx], p.pos).setY(0).normalize().multiplyScalar(6).add(p.pos)
      this.steer(p, tmp, fast, dt, 22)
      return
    }
    // a called scramble: get outside the pocket first
    if (p.escape) {
      if (p.pos.distanceTo(p.escape) > 1.5 && p.pos.z < this.los) {
        this.steer(p, p.escape, 7.2, dt, 26)
        return
      }
      p.escape = null
    }
    // your moves: a juke cuts hard to one side, a spin keeps you going through contact
    if (p.juke && t < p.juke.until) {
      tmp.set(p.juke.dir * 6, 0, 2.2).add(p.pos)
      this.steer(p, tmp, 7.6, dt, 40)
      return
    }
    const clock = this.situation.clock ?? 120
    const nearSideline = Math.abs(p.pos.x) > SIDELINE - 7
    const sidelineCatch = this.play.sideline?.includes(p.key) && p !== this.qb
    if (p.toSideline || (sidelineCatch && since > 0.3) || (clock < 25 && nearSideline && since > 0.3)) {
      // behind the line, get back to it first (bending toward the near side); past it, bend for the boundary
      const side = Math.sign(p.pos.x || p.cutBias || 1)
      if (p.pos.z < this.los + 1) this.steer(p, tmp.set(p.pos.x + side * 4, 0, this.los + 3), 6.6, dt, 16)
      else this.steer(p, tmp.set(side * (SIDELINE + 3), 0, p.pos.z + p.cutBias * 3 + 1.2), 6.5, dt, 14)
      return
    }
    let bestScore = -Infinity
    let bestAngle = 0
    const curAngle = Math.atan2(p.vel.x, Math.max(0.1, p.vel.z))
    for (let a = -1.4; a <= 1.4001; a += 0.2) {
      const dx = Math.sin(a)
      const dz = Math.cos(a)
      const px = p.pos.x + dx * 4
      const pz = p.pos.z + dz * 4
      let clearance = 8
      for (const d of this.players) {
        if (d.team !== 'def' || d.down) continue
        let dd = Math.hypot(d.pos.x + d.vel.x * 0.35 - px, d.pos.z + d.vel.z * 0.35 - pz)
        if (this.isEngaged(d)) dd += 2.5
        clearance = Math.min(clearance, dd)
      }
      let s = dz * 1.6 + clearance * 0.55 - Math.abs(a - curAngle) * 0.35 + p.cutBias * dx * 0.3
      if (Math.abs(px) > SIDELINE - 1) s -= 4
      if (s > bestScore) (bestScore = s), (bestAngle = a)
    }
    tmp.set(Math.sin(bestAngle), 0, Math.cos(bestAngle)).multiplyScalar(6).add(p.pos)
    const speed = p === this.qb ? (p.scramble ? 7.3 : 6.4) : p === this.rb ? 7.2 : since < 0.4 ? 4.8 : 7.3
    this.steer(p, tmp, speed, dt, 16)
  }

  // ------------------------------------------------------------------ defense
  actDefense(p, t, dt) {
    const a = p.assign
    p.hold = null
    if (p.frozenUntil > t) {
      // bit on the fake (or got juked): planted for a beat
      this.brake(p, dt, 9)
      p.face = (this.carrier ?? this.qb).pos
      return
    }
    // a QB scramble: defenders in coverage have their backs turned, so they stay with their man/zone a beat
    const scrambleRead = this.carrier?.scramble && a.type !== 'rush' && t < this.catchTime + 0.6 + p.react
    if (this.carrier && !scrambleRead) {
      // a draw works because the rush keeps charging at the quarterback for a beat after the handoff
      if (this.play.run?.draw && a.type === 'rush' && t < this.catchTime + 0.55) return this.rushQB(p, t, dt)
      if (this.isEngaged(p)) {
        p.hold = 'Block'
        this.steer(p, this.carrier.pos, 1, dt)
        return
      }
      return this.pursue(p, p.speed + (p.role === 'DL' ? 0 : 0.4), dt)
    }
    if (t < SNAP_TIME * 0.6) return
    if (a.type === 'rush') return this.rushQB(p, t, dt)

    const b = this.ball
    const ballRange = a.type === 'man' ? 40 : a.deep ? 22 : 16
    const readDelay = p.react + (a.type === 'zone' && !p.blanket ? 0.25 : 0)
    if (b.state === 'air' && this.aim && t > b.t0 + readDelay && p.pos.distanceTo(this.aim.point) < ballRange) {
      this.steer(p, this.aim.point, p.speed + 0.4, dt, 26)
      p.face = null
      return
    }

    if (a.type === 'man') {
      const r = a.target
      if (t < 0.25 + p.react * 0.4) return
      const lagT = p.blanket ? 0.03 : a.press ? 0.1 + p.react * 0.25 : 0.12 + p.react * 0.35
      const lag = Math.min((r.hist?.length ?? 0) / 2 - 2, Math.round(lagT / dt))
      let vx = 0
      let vz = 0
      if (lag > 0) {
        const h = r.hist
        const i = h.length - 2 - lag * 2
        vx = (h[i] - h[i - 2]) / dt
        vz = (h[i + 1] - h[i - 1]) / dt
        tmp.set(h[i] + vx * lagT, 0, h[i + 1] + vz * lagT)
      } else tmp.copy(r.pos)
      const v = Math.hypot(vx, vz)
      if (r.routeStart > 50) tmp.z += 3
      else if (v > 2) {
        const back = p.blanket ? 0.35 : 0.75
        tmp.x -= (vx / v) * back
        tmp.z -= (vz / v) * back
        tmp.x += r.pos.x > 0 ? -0.3 : 0.3
      } else tmp.z += a.press ? 0.9 : 1.6
      this.steer(p, tmp, p.speed + (p.blanket ? 0.5 : 0), dt, a.press || p.blanket ? 20 : 16)
      p.face = t < 1.0 ? this.qb.pos : null
      return
    }

    // zone: drop to the landmark, then squeeze the most dangerous receiver in your area
    const spot = a.spot
    let threat = null
    let td = Infinity
    for (const o of this.players) {
      if (o.team !== 'off' || !o.route || o.routeStart > 50 || t < o.routeStart || o.runBlocker || o.leadBlock) continue
      const d = o.pos.distanceTo(spot)
      const deeperThanMe = o.pos.z > p.pos.z - 2
      if ((a.deep ? deeperThanMe && d < (a.range ?? 13) : d < 7.5) && d < td) (td = d), (threat = o)
    }
    tmp.copy(spot)
    if (threat) {
      const w = a.deep ? (p.blanket ? 0.8 : p.zoneW) : THREE.MathUtils.clamp(1 - td / 7.5, 0, 1) * 0.85
      tmp2.copy(threat.pos)
      tmp2.z += a.deep ? 2.5 : 0.8
      tmp.lerp(tmp2, w)
      if (a.deep) tmp.z = Math.max(tmp.z, threat.pos.z + (p.blanket ? 1.5 : -1.5))
    }
    tmp.z = Math.min(tmp.z, END_LINE)
    this.steer(p, tmp, a.deep ? p.speed : p.speed - 0.7, dt, 16)
    p.face = this.qb.pos
  }

  rushQB(p, t, dt) {
    if (this.play.type === 'run' && !this.play.run.draw && this.isEngaged(p)) {
      p.hold = 'Block'
      tmp.copy(p.pos).add(tmp2.set(Math.sign(p.pos.x - this.holeX || 1) * 0.8, 0, 0.5))
      this.steer(p, tmp, 1, dt)
      this.look(p, 0, -5)
      return
    }
    const qb = this.qb
    tmp.copy(qb.pos)
    if (p.blocker && Math.abs(p.start.x) > 3 && p.pos.z > qb.pos.z + 2) tmp.x += Math.sign(p.start.x) * 2.2
    const free = !p.blocker
    if (free && p.pos.z > this.los - 2) tmp.set(Math.sign(p.start.x || 1) * 2.5, 0, this.los - 3)
    const engaged = this.isEngaged(p)
    this.steer(p, tmp, engaged ? 0.9 : p.speed + (free ? 0.5 : 0), dt, free ? 24 : 18)
    p.hold = engaged ? 'Block' : null
    p.face = engaged ? qb.pos : null
  }

  // ------------------------------------------------------------------ ball
  /** Lead receiver R: iterate to where he'll be when the ball gets there. probe=true only measures. */
  planThrow(throwStart, R = this.target, probe = false) {
    const release = tmp4.set(this.qb.pos.x, 1.6, this.qb.pos.z)
    const tr = throwStart + THROW_RELEASE
    let ta = tr + 1
    const point = probe ? (this._probePoint ??= new THREE.Vector3()) : new THREE.Vector3()
    for (let i = 0; i < 6; i++) {
      this.routePosAt(R, ta, point)
      const dist = release.distanceTo(point)
      ta = tr + dist / ballSpeed(dist)
    }
    this.routePosAt(R, ta, point)
    if (probe) {
      this._probe = { time: ta, point }
      return
    }
    this.aim = { time: ta, point, release: tr }
    this.throwAt = throwStart
  }

  release(t) {
    const b = this.ball
    b.state = 'air'
    b.holder = null
    b.from.copy(b.pos)
    b.to.copy(this.aim.point).setY(1.25)
    b.t0 = t
    b.t1 = this.aim.time
    b.arc = Math.max(0.6, b.from.distanceTo(b.to) * 0.09)
    this.emit('throw')
  }

  checkPressure(t) {
    const qb = this.qb
    if (this.play.type !== 'pass' || this.ball.holder !== qb || this.carrier === qb || t < SNAP_TIME) return
    let nearest = Infinity
    let who = null
    for (const d of this.players) {
      if (d.team !== 'def' || d.down || this.isEngaged(d)) continue
      const dd = d.pos.distanceTo(qb.pos)
      if (dd < nearest) (nearest = dd), (who = d)
    }
    if (nearest < 1.0 && !(qb.threw && this.aim && t > this.aim.release - 0.1)) return this.sack(t, who)
    if (!qb.threw && !this.pressured && t > 0.7 && nearest / who.speed < 0.6) {
      this.pressured = true
      this.hurried = true
      this.message = 'Under pressure!'
      // he needs a beat to feel it
      for (const r of this.reads) r.at = Math.min(r.at, t + qb.feel)
    }
  }

  sack(t, d) {
    const qb = this.qb
    this.oneShot(d, 'Tackle')
    d.down = true
    d.yaw = Math.atan2(qb.pos.x - d.pos.x, qb.pos.z - d.pos.z)
    d.vel.set(Math.sin(d.yaw), 0, Math.cos(d.yaw)).multiplyScalar(3)
    this.tackler = d
    this.carrier = qb
    this.catchTime = t
    this.phase = 'dead'
    this.deadTime = t
    this.tackleTime = t
    qb.pendingFall = t + 0.18
    const gain = Math.round(qb.pos.z - this.los)
    this.result = { good: false, kind: 'sack', gain, first: false, spot: qb.pos.z, elapsed: t }
    this.message = `SACKED by ${who(d)} for ${gain} yards`
    this.emit('sack', { by: d.number })
  }

  updateBall(t, dt) {
    const b = this.ball
    if (b.state === 'snap' || b.state === 'air') {
      if (b.state === 'snap') b.to.set(this.qb.pos.x, 1.0, this.qb.pos.z + 0.3)
      const u = THREE.MathUtils.clamp((t - b.t0) / (b.t1 - b.t0), 0, 1)
      const prev = tmp.copy(b.pos)
      b.pos.lerpVectors(b.from, b.to, u)
      b.pos.y += 4 * b.arc * u * (1 - u)
      if (b.pos.distanceToSquared(prev) > 1e-8) b.dir.subVectors(b.pos, prev).normalize()
      if (u >= 1) {
        if (b.state === 'snap') {
          b.state = 'held'
          b.holder = this.qb
        } else this.arrive(t)
      }
    } else if (b.state === 'loose') {
      b.vel.y -= 25 * dt
      b.pos.addScaledVector(b.vel, dt)
      if (b.pos.y < 0.12) {
        b.pos.y = 0.12
        b.vel.multiplyScalar(0.4)
        b.vel.y = Math.abs(b.vel.y) * 0.3
      }
    }
  }

  arrive(t) {
    const b = this.ball
    const r = this.target
    let nd = Infinity
    let cover = null
    for (const d of this.players) {
      if (d.team !== 'def' || d.down) continue
      const dd = Math.min(d.pos.distanceTo(r.pos), d.pos.distanceTo(this.aim.point))
      if (dd < nd) (nd = dd), (cover = d)
    }
    const deep = this.aim.point.z - this.los > 20
    const incomplete = (msg) => {
      b.state = 'loose'
      b.holder = null
      this.phase = 'dead'
      this.deadTime = t
      this.result = { good: false, kind: 'incomplete', gain: 0, first: false, spot: this.los, elapsed: t }
      this.message = msg
      this.emit('incomplete')
    }
    const overthrow = 0.06 + (this.hurried ? 0.16 : 0) + (deep ? 0.07 : 0)
    if (this.rng() < overthrow) {
      b.vel.copy(b.dir).multiplyScalar(9).setY(1)
      return incomplete(this.hurried ? `Incomplete! Rushed throw sails past ${who(r)}` : `Incomplete! Overthrown, just past ${who(r)}`)
    }
    const keyed = this.key && this.key.family === this.play.family ? this.key.s : 0
    const mid = !deep && this.aim.point.z - this.los > 8
    const reach = (deep ? 2.8 : mid ? 2.2 : 1.6) + keyed * 0.6
    const pInt = THREE.MathUtils.clamp((reach * 0.8 - nd) / (reach * 0.8), 0, 1) * (deep ? 0.36 : 0.3) * (this.hurried ? 1.4 : 1) * (1 + keyed * 0.8) * (this.staredDown ? 1.5 : 1)
    const pBreak = THREE.MathUtils.clamp((reach - nd) / reach, 0, (deep ? 0.65 : 0.55) + keyed * 0.15)
    const roll = this.rng()
    if (roll < pInt) {
      b.state = 'held'
      b.holder = cover
      this.interceptor = cover
      this.oneShot(cover, 'Catch')
      this.phase = 'dead'
      this.deadTime = t
      this.result = { good: false, kind: 'interception', gain: 0, first: false, spot: this.los, elapsed: t, by: cover.number, byName: cover.name ?? null }
      this.message = `INTERCEPTED by ${who(cover)}!`
      this.emit('interception', { by: cover.number })
      return
    }
    if (roll < pInt + pBreak) {
      b.vel.set((this.rng() - 0.5) * 6, 4, -3)
      return incomplete(`Incomplete! Broken up by ${who(cover)}`)
    }
    if (this.rng() < 0.07) {
      b.vel.set((this.rng() - 0.5) * 3, 3, 1.5)
      return incomplete(`Dropped! ${who(r)} can't hang on`)
    }
    b.state = 'held'
    b.holder = r
    this.carrier = r
    this.catchTime = t
    this.how = 'catch'
    r.cutBias = (this.rng() - 0.5) * 0.6
    this.message = nd < 2 ? 'Caught it in traffic!' : 'Caught it! Run!'
    this.emit('catch')
  }

  checkTackle(t) {
    const c = this.carrier
    if (!c || t < this.catchTime + 0.45) return
    const blast = this.how === 'blast'
    for (const d of this.players) {
      if (d.team !== 'def' || d.locked || d.down || this.isEngaged(d) || d.frozenUntil > t) continue
      const dist = d.pos.distanceTo(c.pos)
      if (dist >= 1.8) continue
      tmp.copy(c.vel).setY(0)
      const fromBehind = tmp.lengthSq() > 4 && tmp.normalize().dot(tmp2.subVectors(c.pos, d.pos).setY(0).normalize()) > 0.6
      if (fromBehind && dist > 1.25) continue
      this.oneShot(d, 'Tackle')
      d.down = true
      d.face = null
      d.yaw = Math.atan2(c.pos.x - d.pos.x, c.pos.z - d.pos.z)
      d.vel.set(Math.sin(d.yaw), 0, Math.cos(d.yaw)).multiplyScalar(4)
      if (blast) this.emit('blast')
      const spinning = c.spinUntil > t
      const make = d.tackle - (fromBehind ? 0.14 : 0) - (d.role === 'DL' && c !== this.rb ? 0.1 : 0) - (blast ? 0.16 : 0) - (spinning ? 0.3 : 0)
      if (this.rng() > make) {
        d.vel.multiplyScalar(0.6)
        d.yaw += (this.rng() - 0.5) * 0.9
        this.message = blast ? 'QB BLAST! Runs right through him!' : spinning ? 'SPIN MOVE! Broke a tackle!' : 'Broke a tackle!'
        c.cutBias = -c.cutBias || 0.3
        this.emit('brokenTackle')
        continue
      }
      this.tackler = d
      const atSideline = Math.abs(c.pos.x) > (this.play.sideline?.includes(c.key) ? 16 : SIDELINE - 1.5)
      this.endPlay(t, atSideline ? 'out' : 'tackle')
      c.pendingFall = t + 0.22
      this.emit(atSideline ? 'out' : 'tackle')
      return
    }
  }

  checkBoundaries(t) {
    const c = this.carrier
    if (!c || this.phase !== 'live') return
    if (c.pos.z >= GOAL_LINE) {
      this.endPlay(t, 'touchdown')
      this.emit('touchdown')
    } else if (Math.abs(c.pos.x) > SIDELINE) {
      this.endPlay(t, 'out')
      this.emit('out')
    }
  }

  endPlay(t, kind) {
    const c = this.carrier
    this.phase = 'dead'
    this.deadTime = t
    this.tackleTime = t
    const spot = kind === 'touchdown' ? GOAL_LINE : c.pos.z
    const first = spot >= this.firstDown
    // just short of the sticks reads as short, not as a rounded-up first-down distance
    const gain = Math.min(Math.round(spot - this.los), first || kind === 'touchdown' ? Infinity : Math.max(0, Math.round(this.firstDown - this.los) - 1))
    this.result = { good: kind === 'touchdown' || first || gain >= 4, kind, gain, first, spot, elapsed: t, how: this.how }
    const how = {
      catch: `Complete to ${who(c)}`,
      run: `${who(c)} runs`,
      blast: `${who(this.qb)} QB BLAST`,
      keep: `${who(this.qb)} keeps it`,
      scramble: `${who(this.qb)} scrambles`,
    }[this.how] ?? `${who(c)} runs`
    const yards = `${gain} yard${Math.abs(gain) === 1 ? '' : 's'}`
    if (kind === 'touchdown') this.message = `TOUCHDOWN! ${how} ${yards}`
    else this.message = `${how} for ${yards}${kind === 'out' ? ', out of bounds' : ''}${first ? ' — FIRST DOWN!' : ''}`
  }

  updateFall(t) {
    const c = this.carrier
    if (c && c.pendingFall && t >= c.pendingFall) {
      c.pendingFall = null
      c.down = true
      this.oneShot(c, c.sliding ? 'Slide' : 'Fall')
      this.ball.state = 'dead'
    }
  }
}

